/// Persistent viewer state; keep one in the app.
pub struct CodexState {
    /// Used by [`show_window`].
    pub open: bool,
    pub selected: Option<String>,
    pub query: String,
    pub category: Option<&'static str>,
    history: Vec<String>,
    /// Optional font family for bold text (e.g. `FontFamily::Name("bold".into())`); falls back to strong colour.
    pub bold_family: Option<FontFamily>,
    /// Optional font family for headings.
    pub heading_family: Option<FontFamily>,
    /// Width of the list pane in two-pane mode.
    pub list_width: f32,
    scroll_to_top: bool,
}

impl Default for CodexState {
    fn default() -> Self {
        Self {
            open: false,
            selected: None,
            query: String::new(),
            category: None,
            history: Vec::new(),
            bold_family: None,
            heading_family: None,
            list_width: 230.0,
            scroll_to_top: false,
        }
    }
}

impl CodexState {
    pub fn new() -> Self {
        Self::default()
    }

    /// Navigate to an entry (records history for the Back button). Also sets `open = true`.
    pub fn open_entry(&mut self, id: &str) {
        if find(id).is_none() {
            return;
        }
        if let Some(cur) = self.selected.take() {
            if cur != id {
                self.history.push(cur);
                if self.history.len() > 64 {
                    self.history.remove(0);
                }
            }
        }
        self.selected = Some(id.to_string());
        self.open = true;
        self.scroll_to_top = true;
    }

    /// Open the entry for a wall material / matter element. Returns false if there is none.
    pub fn open_element(&mut self, element: u32) -> bool {
        match for_element(element) {
            Some(e) => {
                self.open_entry(e.id);
                true
            }
            None => false,
        }
    }

    /// Open the entry for a machine tile. Returns false if there is none.
    pub fn open_tile(&mut self, tile: u32) -> bool {
        match for_tile(tile) {
            Some(e) => {
                self.open_entry(e.id);
                true
            }
            None => false,
        }
    }

    pub fn back(&mut self) {
        if let Some(prev) = self.history.pop() {
            self.selected = Some(prev);
            self.scroll_to_top = true;
        } else {
            self.selected = None;
        }
    }
}

/// What the user asked for inside the viewer (the app decides what to do with it).
#[derive(Default, Clone, Copy, Debug, PartialEq)]
pub struct CodexResponse {
    /// "Use in sandbox" was clicked on an entry with an element id.
    pub use_element: Option<u32>,
    /// "Use in sandbox" was clicked on an entry with a machine tile id.
    pub use_tile: Option<u32>,
}

/// Show the Codex inside any `Ui` (two panes when wide, one pane with a Back button when narrow).
pub fn show(ui: &mut egui::Ui, st: &mut CodexState) -> CodexResponse {
    let mut resp = CodexResponse::default();
    let wide = ui.available_width() >= 560.0;
    if wide {
        let h = ui.available_height();
        ui.horizontal_top(|ui| {
            ui.allocate_ui_with_layout(egui::vec2(st.list_width, h), egui::Layout::top_down(egui::Align::Min), |ui| {
                ui.set_min_size(egui::vec2(st.list_width, h));
                list_pane(ui, st);
            });
            ui.separator();
            ui.allocate_ui_with_layout(egui::vec2(ui.available_width(), h), egui::Layout::top_down(egui::Align::Min), |ui| {
                ui.set_min_size(egui::vec2(ui.available_width(), h));
                entry_pane(ui, st, &mut resp);
            });
        });
    } else if st.selected.is_some() {
        entry_pane(ui, st, &mut resp);
    } else {
        list_pane(ui, st);
    }
    resp
}

/// Convenience: a resizable window around [`show`], open while `st.open` is true.
pub fn show_window(ctx: &egui::Context, st: &mut CodexState) -> CodexResponse {
    let mut open = st.open;
    let mut resp = CodexResponse::default();
    egui::Window::new("Reference manual")
        .open(&mut open)
        .default_size([820.0, 560.0])
        .min_width(320.0)
        .min_height(240.0)
        .resizable(true)
        .collapsible(false)
        .show(ctx, |ui| {
            resp = show(ui, st);
        });
    st.open = open && st.open;
    resp
}

fn list_pane(ui: &mut egui::Ui, st: &mut CodexState) {
    ui.horizontal(|ui| {
        let te = egui::TextEdit::singleline(&mut st.query).hint_text("Search the Codex…").desired_width(ui.available_width());
        ui.add(te);
    });
    ui.add_space(4.0);
    ui.horizontal_wrapped(|ui| {
        ui.spacing_mut().item_spacing = egui::vec2(4.0, 4.0);
        if ui.selectable_label(st.category.is_none(), "All").clicked() {
            st.category = None;
        }
        for c in CATEGORIES {
            if ui.selectable_label(st.category == Some(c), c).clicked() {
                st.category = if st.category == Some(c) { None } else { Some(c) };
            }
        }
    });
    ui.separator();
    let results = search(&st.query);
    let searching = !st.query.trim().is_empty();
    egui::ScrollArea::vertical().id_salt("codex_list").auto_shrink([false, false]).show(ui, |ui| {
        let mut clicked: Option<&'static str> = None;
        if searching {
            for e in results.iter().filter(|e| st.category.map_or(true, |c| e.category == c)) {
                let sel = st.selected.as_deref() == Some(e.id);
                let r = ui.selectable_label(sel, e.title).on_hover_text(e.category);
                if r.clicked() {
                    clicked = Some(e.id);
                }
            }
            if results.is_empty() {
                ui.weak("No entries match.");
            }
        } else {
            for c in CATEGORIES {
                if st.category.map_or(false, |sc| sc != c) {
                    continue;
                }
                let mut items: Vec<&&CodexEntry> = results.iter().filter(|e| e.category == c).collect();
                if items.is_empty() {
                    continue;
                }
                items.sort_by_key(|e| e.title);
                egui::CollapsingHeader::new(RichText::new(format!("{c}  ({})", items.len())).strong())
                    .id_salt(("codex_cat", c))
                    .default_open(st.category.is_some() || c == "Concepts")
                    .show(ui, |ui| {
                        for e in items {
                            let sel = st.selected.as_deref() == Some(e.id);
                            if ui.selectable_label(sel, e.title).clicked() {
                                clicked = Some(e.id);
                            }
                        }
                    });
            }
            // entries whose category isn't in CATEGORIES
            let others: Vec<&&CodexEntry> = results.iter().filter(|e| !CATEGORIES.contains(&e.category)).collect();
            if !others.is_empty() && st.category.is_none() {
                egui::CollapsingHeader::new("Other").id_salt("codex_other").show(ui, |ui| {
                    for e in others {
                        if ui.selectable_label(st.selected.as_deref() == Some(e.id), e.title).clicked() {
                            clicked = Some(e.id);
                        }
                    }
                });
            }
        }
        if let Some(id) = clicked {
            st.open_entry(id);
        }
    });
}

fn entry_pane(ui: &mut egui::Ui, st: &mut CodexState, resp: &mut CodexResponse) {
    let Some(entry) = st.selected.as_deref().and_then(find) else {
        welcome(ui, st);
        return;
    };
    ui.horizontal(|ui| {
        if ui.button("◀ Back").clicked() {
            st.back();
        }
        ui.weak(entry.category);
        ui.with_layout(egui::Layout::right_to_left(egui::Align::Center), |ui| {
            if entry.element.is_some() || entry.tile.is_some() {
                if ui.button("Load into workspace").on_hover_text("Select this material as the active tool").clicked() {
                    resp.use_element = entry.element;
                    resp.use_tile = entry.tile;
                }
            }
        });
    });
    ui.separator();
    let mut sa = egui::ScrollArea::vertical().id_salt("codex_entry").auto_shrink([false, false]);
    if st.scroll_to_top {
        sa = sa.vertical_scroll_offset(0.0);
        st.scroll_to_top = false;
    }
    let style = MdStyle::new(ui, st);
    let mut nav: Option<String> = None;
    sa.show(ui, |ui| {
        ui.set_max_width(ui.available_width().min(760.0));
        if let Some(id) = render_markdown(ui, entry.body_md, &style) {
            nav = Some(id);
        }
        ui.add_space(12.0);
    });
    if let Some(id) = nav {
        st.open_entry(&id);
    }
}

