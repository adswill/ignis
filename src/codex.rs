fn parse(file_id: &'static str, src: &'static str) -> CodexEntry {
    let mut e = CodexEntry { id: file_id, title: file_id, category: "Concepts", body_md: src, element: None, tile: None, tags: "" };
    let s = src.trim_start_matches('\u{feff}');
    if let Some(rest) = s.strip_prefix("---") {
        if let Some(end) = rest.find("\n---") {
            let front = &rest[..end];
            let after = &rest[end + 4..];
            e.body_md = after.strip_prefix('\n').unwrap_or(after);
            for line in front.lines() {
                let Some((k, v)) = line.split_once(':') else { continue };
                let v = v.trim();
                match k.trim() {
                    "id" => e.id = v,
                    "title" => e.title = v,
                    "category" => e.category = v,
                    "element" => e.element = v.parse().ok(),
                    "tile" => e.tile = v.parse().ok(),
                    "tags" => e.tags = v,
                    _ => {}
                }
            }
        }
    }
    e
}

/// All entries, parsed once and cached, in table order.
pub fn all() -> &'static [CodexEntry] {
    static CACHE: OnceLock<Vec<CodexEntry>> = OnceLock::new();
    CACHE.get_or_init(|| FILES.iter().map(|(id, src)| parse(id, src)).collect())
}

/// All entries (owned copy; cheap, the strings are static).
pub fn entries() -> Vec<CodexEntry> {
    all().to_vec()
}

pub fn find(id: &str) -> Option<&'static CodexEntry> {
    all().iter().find(|e| e.id == id)
}

/// Entry for a wall material (0-9) or matter element id (10+), e.g. for an "Open in Codex" button.
pub fn for_element(element: u32) -> Option<&'static CodexEntry> {
    all().iter().find(|e| e.element == Some(element))
}

/// Entry for a machine tile (scene::FAN, scene::IGNITER, ...).
pub fn for_tile(tile: u32) -> Option<&'static CodexEntry> {
    all().iter().find(|e| e.tile == Some(tile))
}

fn contains_ci(hay: &str, needle_lc: &str) -> bool {
    hay.to_lowercase().contains(needle_lc)
}

/// Ranked search over title, id, tags and body. Empty query returns everything.
pub fn search(query: &str) -> Vec<&'static CodexEntry> {
    let q = query.trim().to_lowercase();
    if q.is_empty() {
        return all().iter().collect();
    }
    let words: Vec<&str> = q.split_whitespace().collect();
    let mut scored: Vec<(i32, &'static CodexEntry)> = all()
        .iter()
        .filter_map(|e| {
            let t = e.title.to_lowercase();
            let mut score = 0;
            for w in &words {
                let mut s = 0;
                if t.starts_with(w) {
                    s = 100;
                } else if t.contains(w) || e.id.contains(w) {
                    s = 60;
                } else if contains_ci(e.tags, w) {
                    s = 30;
                } else if contains_ci(e.body_md, w) {
                    s = 5;
                }
                if s == 0 {
                    return None; // every word must match somewhere
                }
                score += s;
            }
            Some((score, e))
        })
        .collect();
    scored.sort_by(|a, b| b.0.cmp(&a.0).then(a.1.title.cmp(b.1.title)));
    scored.into_iter().map(|(_, e)| e).collect()
}

/// A "did you know" line for loading screens / tooltips: (entry id, entry title, "Property: value").
/// Deterministic for a given seed. Picks a row from an entry's "At a glance" table.
pub fn random_fact(seed: u64) -> Option<(&'static str, &'static str, String)> {
    let mut facts: Vec<(&'static CodexEntry, &'static str)> = Vec::new();
    for e in all() {
        for line in e.body_md.lines() {
            let l = line.trim();
            if l.starts_with('|') && !l.contains("---") && !l.starts_with("| Property") {
                facts.push((e, l));
            }
        }
    }
    if facts.is_empty() {
        return None;
    }
    let mut h = seed.wrapping_mul(0x9E37_79B9_7F4A_7C15);
    h ^= h >> 29;
    let (e, row) = facts[(h % facts.len() as u64) as usize];
    let cells = split_row(row);
    let text = if cells.len() >= 2 { format!("{}: {}", cells[0], cells[1]) } else { cells.join(" ") };
    Some((e.id, e.title, strip_inline(&text)))
}

