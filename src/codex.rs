struct MdStyle {
    body: FontId,
    small: FontId,
    h1: FontId,
    h2: FontId,
    h3: FontId,
    bold_family: Option<FontFamily>,
    text: Color32,
    strong: Color32,
    weak: Color32,
    link: Color32,
    code_bg: Color32,
    /// characters the current font can't draw, with ASCII stand-ins
    subs: Vec<(char, &'static str)>,
}

/// Fallbacks for symbols that egui's default fonts lack (used only when the active font has no glyph).
const GLYPH_FALLBACKS: [(char, &str); 13] = [
    ('→', "->"), ('←', "<-"), ('∝', "~"), ('∇', "grad "), ('ṁ', "m'"), ('⁻', "-"), ('⁺', "+"), ('ⁿ', "^n"),
    ('ₐ', "a"), ('ₑ', "e"), ('ₒ', "0"), ('ᵢ', "i"), ('ʻ', "'"),
];

impl MdStyle {
    fn fix(&self, s: &str) -> String {
        if self.subs.is_empty() || !s.chars().any(|c| self.subs.iter().any(|(k, _)| *k == c)) {
            return s.to_string();
        }
        let mut out = String::with_capacity(s.len() + 8);
        for c in s.chars() {
            match self.subs.iter().find(|(k, _)| *k == c) {
                Some((_, r)) => out.push_str(r),
                None => out.push(c),
            }
        }
        out
    }

    fn new(ui: &egui::Ui, st: &CodexState) -> Self {
        let body = egui::TextStyle::Body.resolve(ui.style());
        let hf = st.heading_family.clone().unwrap_or(FontFamily::Proportional);
        let v = ui.visuals();
        let subs = ui.fonts(|f| GLYPH_FALLBACKS.iter().copied().filter(|(c, _)| !f.has_glyph(&body, *c)).collect());
        Self {
            subs,
            small: FontId::new(body.size * 0.85, body.family.clone()),
            h1: FontId::new(body.size * 1.9, hf.clone()),
            h2: FontId::new(body.size * 1.35, hf.clone()),
            h3: FontId::new(body.size * 1.12, hf),
            body,
            bold_family: st.bold_family.clone(),
            text: v.text_color(),
            strong: v.strong_text_color(),
            weak: v.weak_text_color(),
            link: v.hyperlink_color,
            code_bg: v.code_bg_color,
        }
    }
}

#[derive(Clone, Debug, PartialEq)]
enum Span {
    Text { s: String, bold: bool, italic: bool, code: bool },
    Link { target: String, label: String },
}

/// Parse inline markup: **bold**, *italic*, `code`, [[id]] / [[id|label]].
fn parse_inline(src: &str) -> Vec<Span> {
    let mut out = Vec::new();
    let (mut bold, mut italic) = (false, false);
    let mut buf = String::new();
    let b = src.as_bytes();
    let mut i = 0;
    let flush = |buf: &mut String, out: &mut Vec<Span>, bold: bool, italic: bool| {
        if !buf.is_empty() {
            out.push(Span::Text { s: std::mem::take(buf), bold, italic, code: false });
        }
    };
    while i < b.len() {
        let rest = &src[i..];
        if rest.starts_with("[[") {
            if let Some(end) = rest.find("]]") {
                flush(&mut buf, &mut out, bold, italic);
                let inner = &rest[2..end];
                let (target, label) = match inner.split_once('|') {
                    Some((t, l)) => (t.trim().to_string(), l.trim().to_string()),
                    None => {
                        let t = inner.trim().to_string();
                        let l = find(&t).map(|e| e.title.to_string()).unwrap_or_else(|| t.replace('_', " "));
                        (t, l)
                    }
                };
                out.push(Span::Link { target, label });
                i += end + 2;
                continue;
            }
        }
        if rest.starts_with("**") {
            flush(&mut buf, &mut out, bold, italic);
            bold = !bold;
            i += 2;
            continue;
        }
        if rest.starts_with('`') {
            if let Some(end) = rest[1..].find('`') {
                flush(&mut buf, &mut out, bold, italic);
                out.push(Span::Text { s: rest[1..1 + end].to_string(), bold: false, italic: false, code: true });
                i += end + 2;
                continue;
            }
        }
        if rest.starts_with('*') {
            // treat '*' as emphasis only when it hugs a word (avoids "2 * 3")
            // opens only after a space/start/'(' and before a non-space; closes only after a non-space and
            // before a space/end/punctuation (so "p*/p0" and "A* x" stay literal)
            let prev = src[..i].chars().next_back();
            let next = rest[1..].chars().next();
            let can_open = prev.map_or(true, |c| c.is_whitespace() || c == '(') && next.map_or(false, |c| !c.is_whitespace());
            let can_close = prev.map_or(false, |c| !c.is_whitespace()) && next.map_or(true, |c| !c.is_alphanumeric());
            if (italic && can_close) || (!italic && can_open) {
                flush(&mut buf, &mut out, bold, italic);
                italic = !italic;
                i += 1;
                continue;
            }
        }
        let ch = rest.chars().next().unwrap();
        buf.push(ch);
        i += ch.len_utf8();
    }
    flush(&mut buf, &mut out, bold, italic);
    out
}

/// Remove inline markup (for plain-text uses such as tooltips).
pub fn strip_inline(src: &str) -> String {
    parse_inline(src)
        .into_iter()
        .map(|s| match s {
            Span::Text { s, .. } => s,
            Span::Link { label, .. } => label,
        })
        .collect()
}

fn fmt(style: &MdStyle, font: &FontId, bold: bool, italic: bool, code: bool, color: Option<Color32>) -> TextFormat {
    let mut f = font.clone();
    if bold {
        if let Some(bf) = &style.bold_family {
            f.family = bf.clone();
        }
    }
    TextFormat {
        font_id: f,
        color: color.unwrap_or(if bold { style.strong } else { style.text }),
        italics: italic,
        background: if code { style.code_bg } else { Color32::TRANSPARENT },
        ..Default::default()
    }
}

/// Render one paragraph of inline spans. Returns a clicked link target.
fn inline(ui: &mut egui::Ui, style: &MdStyle, spans: &[Span], font: &FontId, color: Option<Color32>) -> Option<String> {
    let has_link = spans.iter().any(|s| matches!(s, Span::Link { .. }));
    if !has_link {
        let mut job = LayoutJob::default();
        job.wrap.max_width = ui.available_width();
        for s in spans {
            if let Span::Text { s, bold, italic, code } = s {
                job.append(&style.fix(s), 0.0, fmt(style, font, *bold, *italic, *code, color));
            }
        }
        ui.add(egui::Label::new(job).wrap());
        return None;
    }
    // with links: flow word by word so links are clickable widgets
    let mut nav = None;
    ui.horizontal_wrapped(|ui| {
        ui.spacing_mut().item_spacing.x = 0.0;
        for s in spans {
            match s {
                Span::Text { s, bold, italic, code } => {
                    let s = style.fix(s);
                    for w in s.split_inclusive(' ') {
                        let mut job = LayoutJob::default();
                        job.append(w, 0.0, fmt(style, font, *bold, *italic, *code, color));
                        ui.add(egui::Label::new(job).extend());
                    }
                }
                Span::Link { target, label } => {
                    let known = find(target).is_some();
                    let text = RichText::new(style.fix(label)).font(font.clone());
                    if known {
                        let r = ui.add(egui::Link::new(text.color(style.link)));
                        let r = match find(target) {
                            Some(e) => r.on_hover_text(e.category),
                            None => r,
                        };
                        if r.clicked() {
                            nav = Some(target.clone());
                        }
                    } else {
                        ui.label(text);
                    }
                }
            }
        }
    });
    nav
}

fn split_row(line: &str) -> Vec<String> {
    let t = line.trim().trim_start_matches('|').trim_end_matches('|');
    t.split('|').map(|c| c.trim().to_string()).collect()
}

fn is_separator_row(line: &str) -> bool {
    let t = line.trim();
    t.starts_with('|') && t.chars().all(|c| matches!(c, '|' | '-' | ':' | ' '))
}

/// Render a markdown-lite document. Returns the target id of a clicked `[[link]]`, if any.
fn render_markdown(ui: &mut egui::Ui, md: &str, style: &MdStyle) -> Option<String> {
    let mut nav = None;
    let lines: Vec<&str> = md.lines().collect();
    let mut i = 0;
    let mut table_n = 0;
    while i < lines.len() {
        let raw = lines[i];
        let line = raw.trim_end();
        let t = line.trim_start();
        if t.is_empty() {
            ui.add_space(style.body.size * 0.45);
            i += 1;
            continue;
        }
        // table block
        if t.starts_with('|') {
            let mut rows: Vec<Vec<String>> = Vec::new();
            while i < lines.len() && lines[i].trim_start().starts_with('|') {
                if !is_separator_row(lines[i]) {
                    rows.push(split_row(lines[i]));
                }
                i += 1;
            }
            let ncol = rows.iter().map(|r| r.len()).max().unwrap_or(1).max(1);
            let total = ui.available_width() - 2.0 * ui.style().spacing.window_margin.sum().x.max(12.0) - 10.0 * ncol as f32;
            let first_w = if ncol == 2 { (total * 0.36).clamp(90.0, 240.0) } else { total / ncol as f32 - 8.0 };
            let other_w = if ncol == 2 { (total - first_w - 16.0).max(80.0) } else { first_w };
            table_n += 1;
            egui::Frame::group(ui.style()).show(ui, |ui| {
                egui::Grid::new(("codex_table", table_n, md.len())).striped(false).min_row_height(style.body.size * 1.45 + 4.0).num_columns(ncol).spacing([12.0, 6.0]).show(ui, |ui| {
                    for (ri, row) in rows.iter().enumerate() {
                        for c in 0..ncol {
                            let cell = row.get(c).map(String::as_str).unwrap_or("");
                            let w = if c == 0 { first_w } else { other_w };
                            let mut job = LayoutJob::default();
                            job.wrap.max_width = w;
                            let header = ri == 0;
                            for s in parse_inline(cell) {
                                match s {
                                    Span::Text { s, bold, italic, code } => {
                                        let col = if header || c == 0 { Some(style.strong) } else { None };
                                        job.append(&style.fix(&s), 0.0, fmt(style, &style.body, bold || header, italic, code, col))
                                    }
                                    Span::Link { label, .. } => job.append(&style.fix(&label), 0.0, fmt(style, &style.body, false, false, false, Some(style.link))),
                                }
                            }
                            ui.allocate_ui(egui::vec2(w, 0.0), |ui| {
                                ui.set_width(w);
                                ui.add(egui::Label::new(job).wrap());
                            });
                        }
                        ui.end_row();
                    }
                });
            });
            continue;
        }
        if let Some(h) = t.strip_prefix("### ") {
            ui.add_space(4.0);
            ui.label(RichText::new(style.fix(&strip_inline(h))).font(style.h3.clone()).color(style.strong));
        } else if let Some(h) = t.strip_prefix("## ") {
            ui.add_space(8.0);
            let h = if h.trim() == "Recipes" { "Reactions" } else if h.trim() == "In Ignis" { "Model behaviour" } else { h };
            ui.label(RichText::new(style.fix(&strip_inline(h))).font(style.h2.clone()).color(style.strong));
            ui.add_space(2.0);
        } else if let Some(h) = t.strip_prefix("# ") {
            ui.label(RichText::new(style.fix(&strip_inline(h))).font(style.h1.clone()).color(style.strong));
        } else if let Some(q) = t.strip_prefix("> ") {
            ui.add_space(4.0);
            let spans = parse_inline(q);
            if let Some(n) = inline(ui, style, &spans, &style.small, Some(style.weak)) {
                nav = Some(n);
            }
        } else if let Some(item) = t.strip_prefix("- ").or_else(|| t.strip_prefix("* ")) {
            let indent = (line.len() - t.len()) as f32 * 4.0;
            ui.horizontal_top(|ui| {
                ui.add_space(6.0 + indent);
                ui.label(RichText::new("•").font(style.body.clone()).color(style.weak));
                ui.vertical(|ui| {
                    if let Some(n) = inline(ui, style, &parse_inline(item), &style.body, None) {
                        nav = Some(n);
                    }
                });
            });
        } else if let Some((num, item)) = numbered(t) {
            ui.horizontal_top(|ui| {
                ui.add_space(6.0);
                ui.label(RichText::new(format!("{num}.")).font(style.body.clone()).color(style.weak));
                ui.vertical(|ui| {
                    if let Some(n) = inline(ui, style, &parse_inline(item), &style.body, None) {
                        nav = Some(n);
                    }
                });
            });
        } else if t == "---" {
            ui.separator();
        } else {
            // paragraph: join following plain lines
            let mut para = t.to_string();
            while i + 1 < lines.len() {
                let n = lines[i + 1].trim();
                if n.is_empty() || n.starts_with('#') || n.starts_with('|') || n.starts_with("- ") || n.starts_with("> ") || numbered(n).is_some() {
                    break;
                }
                para.push(' ');
                para.push_str(n);
                i += 1;
            }
            if let Some(n) = inline(ui, style, &parse_inline(&para), &style.body, None) {
                nav = Some(n);
            }
        }
        i += 1;
    }
    nav
}

fn numbered(t: &str) -> Option<(&str, &str)> {
    let (n, rest) = t.split_once(". ")?;
    if !n.is_empty() && n.len() <= 3 && n.chars().all(|c| c.is_ascii_digit()) {
        Some((n, rest))
    } else {
        None
    }
}

