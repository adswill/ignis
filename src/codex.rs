//! Ignis Codex: the in-game encyclopedia.
//!
//! One Markdown file per element / material / gas / machine / reaction / concept lives in `assets/codex/`
//! and is embedded at compile time (`FILES` below). Each file starts with a small front-matter block:
//!
//! ```text
//! ---
//! id: thermite
//! title: Thermite
//! category: Reactions
//! element: 17        (optional: wall material 0-9 or matter element id 10+)
//! tile: 5            (optional: machine tile id from scene.rs)
//! tags: rust aluminium molten iron
//! ---
//! # Thermite
//! ...
//! ```
//!
//! The body is "markdown-lite": `#`/`##`/`###` headings, `**bold**`, `*italic*`, `` `code` ``, `- ` bullets,
//! `1. ` numbered items, `> ` notes, `| a | b |` tables, and `[[id]]` / `[[id|label]]` cross-links.
//!
//! Public API: [`entries`], [`all`], [`find`], [`for_element`], [`for_tile`], [`search`], [`random_fact`],
//! the [`CodexState`] + [`show`] widget and the [`show_window`] convenience wrapper.
//! The module depends only on `eframe::egui` and std.

use eframe::egui::{self, text::LayoutJob, Color32, FontFamily, FontId, RichText, TextFormat};
use std::sync::OnceLock;

/// One encyclopedia entry. All strings borrow from the embedded files.
#[derive(Clone, Debug)]
pub struct CodexEntry {
    pub id: &'static str,
    pub title: &'static str,
    pub category: &'static str,
    /// Markdown body (front matter stripped).
    pub body_md: &'static str,
    /// Wall material (0-9) or matter element id (10+) this entry describes.
    pub element: Option<u32>,
    /// Machine tile id (scene.rs) this entry describes.
    pub tile: Option<u32>,
    pub tags: &'static str,
}

